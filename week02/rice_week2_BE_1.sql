CREATE DATABASE umc_db;
USE umc_db;

CREATE TABLE users (user_id BIGINT PRIMARY KEY AUTO_INCREMENT, nickname VARCHAR(30) NOT NULL); 
CREATE TABLE category (category_id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(50) NOT NULL); 
CREATE TABLE book (book_id BIGINT PRIMARY KEY AUTO_INCREMENT, category_id BIGINT NOT NULL, title VARCHAR(100) NOT NULL, description TEXT, is_available BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY (category_id) REFERENCES category(category_id)); 
CREATE TABLE rental (rental_id BIGINT PRIMARY KEY AUTO_INCREMENT, user_id BIGINT NOT NULL, book_id BIGINT NOT NULL, rented_at DATETIME NOT NULL, due_at DATETIME NOT NULL, returned_at DATETIME NULL, FOREIGN KEY (user_id) REFERENCES users(user_id), FOREIGN KEY (book_id) REFERENCES book(book_id));


